import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  dhakaCalendarDate,
  formatBengaliPublishDate,
  formatEnglishPublishDate,
  isPostIncludedInBuild,
  loadScheduledBlogPosts,
  type ScheduledBlogPost,
} from "./scheduledPosts";

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_DIR = path.join(ROOT_DIR, "src", "data");
const now = new Date();
const todayDhaka = dhakaCalendarDate(now);
const includeUnpublished = process.argv.includes("--include-unpublished");

function writeIfChanged(filePath: string, content: string): void {
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, "utf8") === content) return;
  fs.writeFileSync(filePath, content, "utf8");
}

function asTs(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

function toBlogMetadata(post: ScheduledBlogPost) {
  const publishDate = post.publishDate ?? post.updatedAt ?? todayDhaka;
  return {
    id: `blog-scheduled-${post.slug}`,
    slug: post.slug,
    title: post.title,
    summary: post.summary,
    category: post.category,
    date: formatEnglishPublishDate(publishDate),
    ...(post.updatedAt ? { updatedAt: post.updatedAt } : {}),
    author: post.author,
    readTime: post.readTime,
    ...(post.references.length ? { references: post.references } : {}),
    internalLinks: post.internalLinksEn,
  };
}

function toBengaliOverride(post: ScheduledBlogPost) {
  const publishDate = post.publishDate ?? post.updatedAt ?? todayDhaka;
  return {
    title: post.titleBn,
    summary: post.summaryBn,
    category: post.categoryBn,
    date: formatBengaliPublishDate(publishDate),
    author: post.authorBn,
    readTime: post.readTimeBn,
    content: post.bengaliBody,
    internalLinks: post.internalLinksBn,
  };
}

function serializeModule(name: string, value: unknown, typeName: string): string {
  return `// Generated by scripts/generate-scheduled-blogs.ts. Do not edit by hand.\nexport const ${name}: ${typeName} = ${asTs(value)};\n`;
}

function generate(posts: ScheduledBlogPost[]): void {
  const indexPosts = posts.map((post) => ({ slug: post.slug, title: post.title }));
  const coverImages = Object.fromEntries(
    posts
      .filter((post) => post.coverImage)
      .map((post) => [post.slug, `/assets/images/${post.coverImage}-1200.webp`]),
  );
  const altText = Object.fromEntries(
    posts
      .filter((post) => post.coverImage && post.coverAltEn && post.coverAltBn)
      .map((post) => [post.slug, { en: post.coverAltEn, bn: post.coverAltBn }]),
  );
  const metadata = posts.map(toBlogMetadata);
  const englishBodies = Object.fromEntries(posts.map((post) => [post.slug, post.englishBody]));
  const bengaliOverrides = Object.fromEntries(posts.map((post) => [post.slug, toBengaliOverride(post)]));
  const seoCopy = Object.fromEntries(
    posts.map((post) => [
      `/blog/${post.slug}`,
      {
        en: {
          ...(post.seoTitle ? { title: post.seoTitle } : {}),
          ...(post.seoDescription ? { description: post.seoDescription } : {}),
        },
        bn: {
          ...(post.seoTitleBn ? { title: post.seoTitleBn } : {}),
          ...(post.seoDescriptionBn ? { description: post.seoDescriptionBn } : {}),
        },
      },
    ]),
  );
  const snippets = Object.fromEntries(
    posts
      .filter((post) => post.snippet || post.snippetBn)
      .map((post) => [post.slug, { ...(post.snippet ? { en: post.snippet } : {}), ...(post.snippetBn ? { bn: post.snippetBn } : {}) }]),
  );
  const faqHeadings = Object.fromEntries(
    posts
      .filter((post) => post.faqHeadingEn && post.faqHeadingBn)
      .map((post) => [post.slug, { en: post.faqHeadingEn, bn: post.faqHeadingBn }]),
  );
  const imageMap = Object.fromEntries(
    posts
      .filter((post) => post.coverImage)
      .map((post) => [post.slug, `${post.coverImage}.jpg`]),
  );

  writeIfChanged(
    path.join(OUTPUT_DIR, "scheduledBlogIndex.generated.ts"),
    [
      "// Generated by scripts/generate-scheduled-blogs.ts. Do not edit by hand.",
      `export const SCHEDULED_BLOG_SLUGS = ${asTs(indexPosts.map(({ slug }) => slug))} as const;`,
      serializeModule("SCHEDULED_BLOG_DIRECTORY", indexPosts, "{ slug: string; title: string }[]"),
      serializeModule("SCHEDULED_BLOG_COVER_IMAGES", coverImages, "Record<string, string>"),
      serializeModule("SCHEDULED_BLOG_ALT_TEXT", altText, "Record<string, { en: string; bn: string }>"),
    ].join("\n"),
  );

  writeIfChanged(
    path.join(OUTPUT_DIR, "scheduledBlogPosts.generated.ts"),
    [
      'import type { BlogPost } from "../types";',
      serializeModule("SCHEDULED_BLOG_DATA", metadata, "BlogPost[]"),
    ].join("\n"),
  );
  writeIfChanged(
    path.join(OUTPUT_DIR, "scheduledBlogBodies.generated.ts"),
    serializeModule("SCHEDULED_BLOG_BODY", englishBodies, "Readonly<Record<string, string>>"),
  );
  writeIfChanged(
    path.join(OUTPUT_DIR, "scheduledBengaliBlogs.generated.ts"),
    serializeModule("SCHEDULED_BENGALI_BLOG_OVERRIDES", bengaliOverrides, "Record<string, { title: string; summary: string; category: string; date: string; author: string; readTime: string; content: string; internalLinks: { text: string; path: string }[] }>"),
  );
  writeIfChanged(
    path.join(OUTPUT_DIR, "scheduledBlogSeo.generated.ts"),
    [
      serializeModule("SCHEDULED_BLOG_SEO_COPY", seoCopy, "Record<string, { en: { title?: string; description?: string }; bn: { title?: string; description?: string } }>"),
      serializeModule("SCHEDULED_BLOG_SNIPPETS", snippets, "Record<string, { en?: string; bn?: string }>"),
      serializeModule("SCHEDULED_BLOG_FAQ_HEADINGS", faqHeadings, "Record<string, { en: string; bn: string }>"),
      serializeModule("SCHEDULED_BLOG_IMAGE_MAP", imageMap, "Record<string, string>"),
    ].join("\n"),
  );
}

try {
  const allPosts = loadScheduledBlogPosts();
  const included = allPosts
    .filter((post) => isPostIncludedInBuild(post, now, includeUnpublished))
    .sort((a, b) => (a.publishDate ?? a.updatedAt ?? "").localeCompare(b.publishDate ?? b.updatedAt ?? ""));
  generate(included);
  const excluded = allPosts.length - included.length;
  console.log(
    `[Scheduled blogs] Generated ${included.length} ${includeUnpublished ? "preview" : "publishable"} post(s); ${excluded} draft/future post(s) remain hidden. Dhaka date: ${todayDhaka}.`,
  );
} catch (error) {
  console.error(error);
  process.exitCode = 1;
}
