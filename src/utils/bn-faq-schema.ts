/**
 * Page-specific helper for Bengali FAQ schema — mirrors getFaqSchemaForPage
 * in faqSchema.ts but returns Bengali (bn) locale data only.
 */
export function getBnFaqSchemaForPage(
  page: "flights" | "hotels" | "visa" | "costs" | "destinations" | "tools" | "contact" | "services" | "sitemap" | "pre-departure",
  parameterId?: string,
  isLanding?: boolean,
  pageUrl?: string,
  routeItems?: readonly RouteFaqEntry[]
): FaqPageSchema | null {
  let faqs: FAQItem[] = [];
  let pageName = "";

  switch (page) {
    case "flights": {
      if (isLanding || !parameterId) {
        faqs = BN_LANDING_FLIGHT_FAQS;
        pageName = "ঢাকা থেকে ফ্লাই - সচরাচর জিজ্ঞাসা";
      } else {
        const route = routeItems?.find((r) => r.id === parameterId) || routeItems?.[0];
        if (!route) return null;
        faqs = route.faqs;
        pageName = `Dhaka to ${route.to ?? "Destination"} Flight Guide FAQs`;
      }
      break;
    }

    case "hotels": {
      if (isLanding || !parameterId) {
        faqs = BN_LANDING_HOTEL_FAQS;
        pageName = "আন্তর্জাতিক হোটেল গাইড বাংলাদেশি ভ্রমণকারীদের জন্য সচরাচর জিজ্ঞাসা";
      } else {
        const hotel = routeItems?.find((h) => h.id === parameterId) || routeItems?.[0];
        if (!hotel) return null;
        faqs = hotel.faqs;
        pageName = `${hotel.city ?? "City"} Hotels & Neighborhood Guide FAQs`;
      }
      break;
    }

    case "visa": {
      if (isLanding || !parameterId) {
        faqs = BN_LANDING_VISA_FAQS;
        pageName = "বাংলাদেশি পাসপোর্টধারীদের ভিসা প্রয়োজনীয়তা সচরাচর জিজ্ঞাসা";
      } else {
        const visa = routeItems?.find((v) => v.id === parameterId) || routeItems?.[0];
        if (!visa) return null;
        faqs = visa.faqs;
        pageName = `${visa.country ?? "Country"} Visa Guide for Bangladeshis FAQs`;
      }
      break;
    }

    case "costs": {
      if (isLanding || !parameterId) {
        faqs = BN_LANDING_COST_FAQS;
        pageName = "ট্রিপ বাজেটিং ও খরচ BDT এ সচরাচর জিজ্ঞাসা";
      } else {
        const cost = routeItems?.find((c) => c.id === parameterId) || routeItems?.[0];
        if (!cost) return null;
        faqs = cost.faqs;
        pageName = `${cost.country ?? "Country"} Travel Budget & Expenses in BDT FAQs`;
      }
      break;
    }

    case "destinations": {
      if (isLanding || !parameterId) {
        faqs = BN_LANDING_DESTINATION_FAQS;
        pageName = "বাংলাদেশ থেকে জনপ্রিয় আন্তর্জাতিক গন্তব্য সচরাচর জিজ্ঞাসা";
      } else {
        const destination = routeItems?.find((d) => d.id === parameterId) || routeItems?.[0];
        if (!destination) return null;
        faqs = destination.faqs;
        pageName = `${destination.country ?? "Country"} Trip Plan & Travel Itinerary FAQs`;
      }
      break;
    }

    case "tools": {
      faqs = BN_SERVICE_TOOLS_FAQS;
      pageName = "বাংলাদেশি ভ্রমণকারী ইউটিলিটি টুলস সচরাচর জিজ্ঞাসা";
      break;
    }

    case "contact": {
      faqs = BN_SERVICE_CONTACT_FAQS;
      pageName = "ট্রাভেল ডেস্ক জিজ্ঞাসা ও WhatsApp বুকিং সহায়তা সচরাচর জিজ্ঞাসা";
      break;
    }

    case "services": {
      faqs = BN_SERVICE_TRAVEL_SERVICES_FAQS;
      pageName = "আন্তর্জাতিক ভ্রমণ সেবা (eSIM, ٹران্সফার, অ্যাক্টিভিটি) সচরাচর জিজ্ঞাসা";
      break;
    }

    case "sitemap":
    case "pre-departure": {
      faqs = BN_PRE_DEPARTURE_SITEMAP_FAQS;
      pageName = "ঢাকা বিমানবন্দর (DAC) প্রি-ডিপার্চার রেডাইনেস, ব্যাগেজ ও এসি জরুরি হাব সচরাচর জিজ্ঞাসা";
      break;
    }

    default:
      return null;
  }

  return generateFaqSchema(faqs, {
    url: pageUrl,
    name: pageName,
  });
}
